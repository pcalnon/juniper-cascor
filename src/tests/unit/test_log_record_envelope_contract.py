_SRC = Path(__file__).resolve().parents[2]
_REPO = _SRC.parent
_FIXTURES = _SRC / "tests" / "fixtures" / "log_envelope"
_GOLDEN_PATH = _FIXTURES / "envelope_golden.json"
_EMITTER = Path(emitter.__file__).resolve()
_CAPTURE = os.environ.get("LOG_ENVELOPE_CAPTURE") == "1"

GOLDEN = json.loads(_GOLDEN_PATH.read_text(encoding="utf-8")) if _GOLDEN_PATH.is_file() or not _CAPTURE else {}
