class TestEnvelopeChecker:
    @pytest.mark.parametrize("name", sorted(REFERENCE["captures"]))
    def test_reference_captures_classify(self, name):
        lines = (_FIXTURES / name).read_text(encoding="utf-8").splitlines()
        assert len(lines) == REFERENCE["captures"][name]["kept_lines"], f"{name} does not match its provenance record"
        for line in lines:
            # A line that LOOKS like a record (a '+' or a bracketed .py prefix) must classify. A
            # non-record line (a tensor repr continuing the previous record, a warning, uvicorn) may
            # not look like one at all.
            if line.startswith("+") or (line.startswith("[") and ".py:" in line[:80]):
                assert envelope.classify(line)[0] is not None, f"{name}: malformed record {line!r}"
        shapes = sorted({envelope.classify(line)[0] for line in lines} - {None})
        _golden_section("reference_capture_shapes", shapes, subkey=name)

    GOOD = {
        "A_FILE": "+[cascade_correlation.py: fit:2006] (2026-09-22 03:27:56) [INFO] CascadeCorrelationNetwork: fit: Training completed.",
        "A_CONSOLE": "+[candidate_unit.py: 762] (2026-09-22 03:27:45) [INFO] CandidateUnit: train: Epoch 10 - Norm Output: shape=(800,)",
        "STD_FILE_S": "[cascade_correlation.py: fit:2006] (2026-09-22 03:27:56) [INFO] CascadeCorrelationNetwork: fit: Training completed.",
        "STD_FILE_MS": "[monitor.py: on_cascade_add:350] (2026-09-01 05:38:00,489) [INFO] Cascade unit 1 added (correlation=0.0000)",
    }

    def test_good_records_classify(self):
        for shape, line in self.GOOD.items():
            assert envelope.classify(line)[0] == shape, (shape, line)

    @pytest.mark.parametrize(
        "shape,old,new",
        [
            ("A_FILE", "+[", "["),  # sentinel dropped: a Path A record now reads as a stdlib one
            ("A_FILE", "+[", "+ ["),  # sentinel detached
            ("A_FILE", "03:27:56)", "03:27:56,123)"),  # milliseconds added to Path A
            ("A_FILE", "2026-09-22 03:27:56", "2026-09-22T03:27:56"),  # ISO 'T' separator
            ("A_FILE", "(2026-09-22", "(26-09-22"),  # two-digit year
            ("A_FILE", "[INFO]", "INFO:"),  # level bracket lost
            ("A_FILE", " fit:2006]", " fit:]"),  # line number lost
            ("A_FILE", "cascade_correlation.py: fit:2006]", "cascade_correlation.py:2006]"),  # func lost, spacing changed
            ("A_CONSOLE", "(2026-09-22 03:27:45)", "2026-09-22 03:27:45"),  # timestamp parentheses lost
            ("STD_FILE_S", "03:27:56)", "03:27:56.123456)"),  # microseconds
            ("STD_FILE_MS", ",489)", ",48)"),  # truncated milliseconds
        ],
    )
    def test_broken_records_are_rejected(self, shape, old, new):
        good = self.GOOD[shape]
        assert old in good, f"mutation {old!r} does not apply to {good!r}"
        broken = good.replace(old, new, 1)
        assert envelope.classify(broken)[0] != shape, f"checker ACCEPTED a broken {shape} record: {broken!r}"
