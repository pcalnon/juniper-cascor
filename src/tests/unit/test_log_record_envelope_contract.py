class TestMarkerInventory:
    def test_inventory_is_well_formed(self):
        assert INVENTORY["generated_by"].endswith("2026-09-22_p04_log_marker_census.py")
        seen = set()
        for marker in INVENTORY["markers"]:
            key = tuple(marker["fragments"])
            assert key and key not in seen, f"empty or duplicate marker {key}"
            seen.add(key)
            assert marker["sites"] and marker["consumers"], marker
            for site in marker["sites"]:
                assert (_REPO / site["file"]).is_file(), f"inventory names a file that does not exist: {site['file']}"

    def test_every_inventoried_marker_is_still_emitted_at_its_level(self):
        failures = []
        for marker in INVENTORY["markers"]:
            found = [s for site in {s["file"] for s in marker["sites"]} for s in envelope.find_marker_sites(_REPO, site, marker["fragments"])]
            levels = [envelope.METHOD_LEVELS[s.method] for s in found if s.method in envelope.METHOD_LEVELS]
            required = marker["required_level"]
            if not found:
                failures.append(f"GONE   {marker['fragments']!r} -- no literal carries it any more; consumers: {marker['consumers']}")
            elif required is not None and (not levels or max(levels) < required):
                failures.append(f"LOWERED {marker['fragments']!r} -- needs a logger call at level >= {required}, found {[(s.file, s.line, s.method) for s in found]}; consumers: {marker['consumers']}")
        assert not failures, "juniper-ml anchors on these markers and will stop matching them:\n" + "\n".join(failures)

    def test_the_resolver_can_say_no(self):
        # Negative controls: a marker emitted nowhere, and a real marker with its fragments swapped
        # (order is part of the contract), must both resolve to NO site.
        target = "src/cascade_correlation/cascade_correlation.py"
        assert envelope.find_marker_sites(_REPO, target, ["P0.4 negative control: emitted nowhere"]) == []
        assert envelope.find_marker_sites(_REPO, target, [" processes", "train_candidates: Executing candidate training with "]) == []
        assert envelope.find_marker_sites(_REPO, target, ["train_candidates: Executing candidate training with ", " processes"]) != []


