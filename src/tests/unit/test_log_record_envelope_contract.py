"""P0.4 (cascor#573): the log-record envelope and named-marker contract, enforced in cascor CI.

Project:     juniper-cascor
Sub-Project: logging
Author:      Paul Calnon
License:     MIT License

WHY THIS FILE EXISTS
cascor's log records are parsed by scripts in juniper-ml: they split worker from parent records
on the ``+`` sentinel, parse the ``(timestamp)`` -- three of them only at SECOND resolution --
anchor on the ``func:LINE]`` prefix, and match 34 distinct message markers such as
``fit: Training completed.``. Every one of those breakages is invisible here: change the message,
drop the sentinel or add milliseconds, and cascor's suite stays green while the analysis tooling
silently stops matching. A test in juniper-ml cannot fail a cascor PR -- separate repositories, no
status-check propagation -- so the contract has to be enforced HERE (roadmap P0.4(d) option (i),
in juniper-ml ``notes/JUNIPER_2026-09-02_JUNIPER-CASCOR_LOGGING-REDESIGN-ROADMAP.md`` §3.1).

WHAT IT PINS, AND HOW EACH PART CAN FAIL

1. **The formatter goldens** -- Path A's constants, Path B's whole ``conf/logging_config.yaml``
   (levels and handlers too: setting the ``juniper`` logger to WARNING would delete every
   run-verdict marker, since those are INFO records), and Path C's installed handlers, including
   the rotation parameters juniper-ml globs against.
2. **The real emit path** -- a CHILD PROCESS (``helpers/log_envelope_emitter.py``) drives all
   three writers into one file. It has to be a child: ``conftest.py``'s session-scoped
   ``_cache_logging_system`` replaces ``Logger._log_at_level`` with a no-op for the whole session,
   so any in-process emit would pass whatever the envelope looked like. Records are compared
   byte-for-byte (modulo the timestamp VALUE, whose FORMAT and precision are checked), and each
   record's ``func:LINE`` against the emitter's own AST -- which makes this the detector for
   roadmap P2.1 (moving frame capture inside ``_log_at_level``).
3. **The named markers** -- every message fragment juniper-ml anchors on must still exist, IN
   ORDER, in one string literal of the file that emits it, inside a logger call at or above the
   level the consumers rely on. ``fixtures/log_envelope/marker_inventory.json`` is generated by
   juniper-ml ``util/ad-hoc/2026-09-22_p04_log_marker_census.py`` and names every consumer.
4. **The checker itself** -- negative controls prove it can say NO: a broken record must fail
   to classify. Without them a regex loose enough to accept anything would pass every test above.

WHEN THIS FAILS
Read ``fixtures/log_envelope/README.md``. A failure here means juniper-ml tooling will stop
matching; the message names the consumers. Update the consumer (and regenerate the inventory) in
the same change, or do not make the change. To re-capture after an INTENDED envelope change:
``LOG_ENVELOPE_CAPTURE=1 pytest src/tests/unit/test_log_record_envelope_contract.py`` rewrites the
golden, then review the diff.
"""

