_TS_FORMAT = "%Y-%m-%d %H:%M:%S"
_MARK = "P0.4 reference record: "


def _golden_section(key: str, observed, subkey: str | None = None):
    """Compare *observed* to ``GOLDEN[key]`` (or ``GOLDEN[key][subkey]``), or rewrite it in capture mode."""
    if _CAPTURE:
        if subkey is None:
            GOLDEN[key] = observed
        else:
            GOLDEN.setdefault(key, {})[subkey] = observed
        _GOLDEN_PATH.write_text(json.dumps(GOLDEN, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        pytest.skip(f"LOG_ENVELOPE_CAPTURE=1: rewrote {key!r} in {_GOLDEN_PATH.name}")
    want = GOLDEN[key] if subkey is None else GOLDEN[key][subkey]
    where = f"{key}/{subkey}" if subkey else key
    assert observed == want, f"the {where!r} envelope contract changed.\n  golden:   {want!r}\n  observed: {observed!r}\njuniper-ml parses this surface (see {_FIXTURES.relative_to(_REPO)}/README.md). If the change is intended, update the consumers and re-capture with LOG_ENVELOPE_CAPTURE=1."


def _expected_calls(func_name: str) -> list[tuple[int, str, str]]:
    """(line, method, rendered message) for each single-line call in ``emitter.<func_name>``."""
    tree = ast.parse(_EMITTER.read_text(encoding="utf-8"))
    func = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == func_name)
    out = []
    for stmt in func.body:
        call = stmt.value if isinstance(stmt, ast.Expr) else None
        if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Attribute):
            continue
        first = call.args[0]
        if isinstance(first, ast.Constant):
            message = first.value
        else:  # the %-args record: PERCENT_ARGS_TEMPLATE, *PERCENT_ARGS_VALUES
            message = emitter.PERCENT_ARGS_TEMPLATE % emitter.PERCENT_ARGS_VALUES
        out.append((call.lineno, call.func.attr, message))
    assert out, f"no calls found in {func_name} -- the emitter's AST contract is broken"
    return out


@pytest.fixture(scope="module")
def emitted(tmp_path_factory):
    """Run the emitter ONCE per module in a fresh interpreter; return every sink it wrote."""
    root = tmp_path_factory.mktemp("log_envelope")
    log_dir = root / "logs"
    report_path = root / "report.json"
    env = {k: v for k, v in os.environ.items() if k not in {"CASCOR_LOG_LEVEL", "JUNIPER_CASCOR_LOG_LEVEL"}}
    env["JUNIPER_CASCOR_LOG_DIR"] = str(log_dir)
    t0 = datetime.datetime.now().replace(microsecond=0) - datetime.timedelta(seconds=1)
    proc = subprocess.run(  # nosec B603 -- fixed interpreter, repo-local script, no user input
        [sys.executable, str(_EMITTER), str(report_path)],
        cwd=_SRC,
        env=env,
        capture_output=True,
        text=True,
        timeout=50,
    )
    t1 = datetime.datetime.now() + datetime.timedelta(seconds=1)
    assert proc.returncode == 0, f"emitter failed: rc={proc.returncode}\nstderr tail:\n{proc.stderr[-3000:]}"
    report = json.loads(report_path.read_text(encoding="utf-8"))
    log_file = Path(report["path_a"]["logging_file"])
    assert log_file.parent == log_dir, f"the file sink is {log_file}, not inside {log_dir}: the JUNIPER_CASCOR_LOG_DIR override did not reach the logger"
    assert log_file.is_file(), f"no file sink at {log_file}"
    return {
        "stdout": proc.stdout.splitlines(),
        "stderr": proc.stderr.splitlines(),
        "file": log_file.read_text(encoding="utf-8").splitlines(),
        "report": report,
        "log_dir": log_dir,
        "window": (t0, t1),
    }


def _ours(lines: list[str]) -> list[str]:
    return [line for line in lines if _MARK in line]


def _check_ts(ts: str, window) -> None:
    parsed = datetime.datetime.strptime(ts, _TS_FORMAT)  # raises on ANY other precision or layout
    assert window[0] <= parsed <= window[1], f"timestamp {ts} is outside the run window {window}"


