class TestRealEmitPath:
    def test_all_three_writers_share_one_file_in_the_override_dir(self, emitted):
        # juniper-ml globs ``logs/juniper_cascor.log*`` (RECON N-4, ~17 consumers); the three writers
        # sharing ONE name, one of which rotates it, is the N-9 hazard P3.3 exists to settle.
        name = GOLDEN["path_a"]["log_file_name"]
        assert Path(emitted["report"]["path_a"]["logging_file"]) == emitted["log_dir"] / name
        file_handlers = [h for section in ("path_b", "path_c") for h in emitted["report"][section]["handlers"] if "filename" in h]
        assert [h["filename"] for h in file_handlers] == [name, name], file_handlers

    @pytest.mark.parametrize("sink,shape", [("file", "A_FILE"), ("stdout", "A_CONSOLE")])
    def test_path_a_records_are_byte_exact_in_both_sinks(self, emitted, sink, shape):
        lines = [line for line in _ours(emitted[sink]) if line.startswith("+")]
        expected = _expected_calls("emit_path_a")
        assert len(lines) == len(expected), f"{sink}: expected {len(expected)} Path A records, got {len(lines)}:\n" + "\n".join(lines)
        for line, (lineno, method, message) in zip(lines, expected, strict=True):
            got_shape, match = envelope.classify(line)
            assert got_shape == shape, f"{sink}: not a {shape} record: {line!r}"
            _check_ts(match.group("ts"), emitted["window"])
            want = envelope.render_path_a("file" if sink == "file" else "console", file=_EMITTER.name, func="emit_path_a", line=lineno, ts=match.group("ts"), level=method.upper(), msg=message)
            assert line == want, f"{sink} record differs from the contract:\n  want {want!r}\n  got  {line!r}"

    def test_path_a_resolves_the_real_caller(self, emitted):
        # Stated separately from the byte-exact test so a P2.1 regression fails with a message
        # that says what is wrong, rather than as a diff of two long lines.
        records = [envelope.classify(line)[1] for line in _ours(emitted["file"]) if line.startswith("+")]
        funcs = sorted({m.group("func") for m in records})
        assert funcs == ["emit_path_a"], f"Path A records name {funcs} as their caller, not 'emit_path_a'. If you are moving frame capture inside _log_at_level (roadmap P2.1), pass cls._frm().f_back from _log_at_level and leave _frame_info's one-hop contract alone (test_logger_frame_resolution.py pins it)."

    def test_stdout_carries_only_records(self, emitted):
        # juniper-ml's launchers redirect stdout into a file its tools parse line by line; a stray
        # print() lands there as an unparseable line.
        strays = [line for line in emitted["stdout"] if envelope.classify(line)[0] not in ("A_CONSOLE", "STD_CONSOLE")]
        assert strays == [], f"non-record lines on stdout: {strays}"
        assert len(emitted["stdout"]) >= len(_expected_calls("emit_path_a")), "stdout is (nearly) empty -- a check over zero lines proves nothing"

    def test_path_b_file_records(self, emitted):
        lines = [line for line in _ours(emitted["file"]) if "path B" in line]
        expected = [call for call in _expected_calls("emit_path_b") if call[1] != "debug"]
        assert len(lines) == len(expected), f"expected {len(expected)} Path B records (DEBUG suppressed by the juniper logger's INFO level), got:\n" + "\n".join(lines)
        for line, (lineno, method, message) in zip(lines, expected, strict=True):
            shape, match = envelope.classify(line)
            assert shape == "STD_FILE_S", f"not a second-resolution stdlib file record: {line!r}"
            _check_ts(match.group("ts"), emitted["window"])
            assert (match.group("file"), match.group("func"), int(match.group("line")), match.group("level"), match.group("msg")) == (_EMITTER.name, "emit_path_b", lineno, method.upper(), message)

    def test_path_b_error_also_reaches_stdout_with_a_two_digit_year(self, emitted):
        lineno, _method, message = next(call for call in _expected_calls("emit_path_b") if call[1] == "error")
        lines = [line for line in _ours(emitted["stdout"]) if "path B" in line]
        assert len(lines) == 1, lines
        match = envelope.STD_CONSOLE.match(lines[0])
        assert match, f"not the conf/logging_config.yaml console shape: {lines[0]!r}"
        assert (match.group("file"), int(match.group("line")), match.group("level"), match.group("msg")) == (_EMITTER.name, lineno, "ERROR", message)

    def test_path_c_file_record_has_millisecond_precision(self, emitted):
        lines = [line for line in _ours(emitted["file"]) if "path C" in line]
        expected = [call for call in _expected_calls("emit_path_c") if call[1] != "debug"]
        assert len(lines) == len(expected), lines
        shape, match = envelope.classify(lines[0])
        assert shape == "STD_FILE_MS", f"Path C's RotatingFileHandler has no datefmt, so its records carry ',mmm': {lines[0]!r}"
        assert (match.group("func"), int(match.group("line"))) == ("emit_path_c", expected[0][0])


